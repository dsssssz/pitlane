// v149: Главная — герой (рендер концепт-машины без марки + вордмарк PITLANE), «Старт», лента машин.
import fs from 'fs';
let fails = 0; const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails++; };
const root = new URL('../../', import.meta.url);
const html = fs.readFileSync(new URL('index.html', root), 'utf8');
const app = fs.readFileSync(new URL('app.js', root), 'utf8');
const css = fs.readFileSync(new URL('styles.css', root), 'utf8');
const sw = fs.readFileSync(new URL('sw.js', root), 'utf8');
const h = html.slice(html.indexOf('id="h48"'), html.indexOf('</section>', html.indexOf('id="h48"')));
const iHero = h.indexOf('id="h49Hero"'), iStart = h.indexOf('id="h48Start"'), iCar = h.indexOf('id="h48Car"'), iGps = h.indexOf('id="h48Gps"'), iStrip = h.indexOf('id="h49Strip"');
ok(iHero > 0 && iHero < iStart && iStart < iCar && iCar < iGps && iGps < iStrip, 'порядок: герой → Старт → машина → GPS → лента');
ok(/<b class="h49-word">PITLANE<\/b>/.test(h) && !/<img[^>]*(logo|emblem|badge)/i.test(h), 'вордмарк — текст, без логотипов');
const st = fs.statSync(new URL('img/home/hero-v149.webp', root));
ok(st.size > 5000 && st.size < 200 * 1024, 'герой webp < 200 KB');
ok(sw.includes("'./img/home/hero-v149.webp'"), 'герой в precache SW');
ok(/data-h49-car=/.test(app) && /carThumbUrl\(m\.id\)/.test(app) && /goToView\('garage'\);[\s\S]{0,80}pickPodiumCar\(id\)/.test(app), 'лента: миниатюры из img/cars, тап → Гараж + выбор машины');
const c = css.slice(css.indexOf('/* ===== v149: Главная'));
ok(/\.h49-strip \{ display: flex;[^}]*overflow-x: auto/.test(c), 'лента скроллится горизонтально');
ok(/grayscale\(/.test(c), 'миниатюры приглушены (тёмные)');
ok(!/text-shadow|drop-shadow|blur\(|orange|#ff9|#30d158/.test(c.slice(0, c.indexOf('/* ===== v150') > 0 ? c.indexOf('/* ===== v150') : undefined)), 'без неона/оранжевого');
ok(/v149/.test(app.match(/APP_VERSION = '([^']+)'/)[1]) || +app.match(/APP_VERSION = 'v(\d+)'/)[1] >= 149, 'версия ≥ v149');
if (fails) { console.log('FAIL', fails); process.exit(1); } console.log('v149 OK');
